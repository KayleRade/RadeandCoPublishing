    function normalizePost(post) {
        return clonePost(post);
    }

    window.RADE_BLOG_LIBRARY = {
        getAllPosts() {
            return posts.map(normalizePost);
        },
        getFeaturedPost() {
            const featured = posts.find((entry) => entry.featured) || posts[0];
            return featured ? normalizePost(featured) : null;
        },
        getPostBySlug(slug) {
            const post = posts.find((entry) => entry.slug === slug);
            return post ? normalizePost(post) : null;
        },
        getRelatedPosts(slug, limit) {
            const current = posts.find((entry) => entry.slug === slug);
            if (!current) {
                return [];
            }

            const sameCategory = posts.filter((entry) => entry.slug !== slug && entry.category === current.category);
            const nearby = posts.filter((entry) => entry.slug !== slug && entry.category !== current.category);
            return [...sameCategory, ...nearby].slice(0, limit || 3).map(normalizePost);
        }
    };
